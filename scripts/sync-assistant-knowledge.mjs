import fs from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createHash } from "node:crypto";
import ts from "typescript";
const web = fileURLToPath(new URL("../", import.meta.url));
const backend = path.resolve(web, "../ChurchOS-Backend/src/assistant");
async function source(relative) { return fs.readFile(path.join(web, relative), "utf8"); }
async function load(relative) {
  const code = ts.transpileModule(await source(relative), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
  return import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
}
const { helpArticles, HELP_REVIEWED_AT } = await load("src/lib/help/catalog.ts");
// helpArticles is used only by helpSearchIndex; the exported content is independent.
const contentSource = (await source("src/lib/help/content.ts")).replace(/^import .*from .*;\s*$/m, "");
const contentCode = ts.transpileModule(contentSource, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { helpContent } = await import(`data:text/javascript;base64,${Buffer.from(contentCode).toString("base64")}`);
const { assistantPolicies } = await load("src/lib/assistant/policies.ts");
const tree = ts.createSourceFile("sidebar.tsx", await source("src/components/layouts/sidebar.tsx"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
function literal(node) {
  if (ts.isArrayLiteralExpression(node)) return node.elements.map(literal);
  if (ts.isObjectLiteralExpression(node)) return Object.fromEntries(node.properties.filter(p => ts.isPropertyAssignment(p) && p.name.getText(tree) !== "icon").map(p => [p.name.getText(tree).replace(/['"]/g, ""), literal(p.initializer)]));
  if (ts.isStringLiteral(node) || ts.isNumericLiteral(node)) return node.text;
  if (node.kind === ts.SyntaxKind.TrueKeyword) return true;
  if (node.kind === ts.SyntaxKind.FalseKeyword) return false;
  throw new Error(`Unsupported navigation node: ${node.getText(tree)}`);
}
let navigation;
function visit(node) { if (ts.isVariableDeclaration(node) && node.name.getText(tree) === "navItems") navigation = literal(node.initializer); ts.forEachChild(node, visit); }
visit(tree);
if (!navigation) throw new Error("Navigation catalog not found");
const leaves = [];
function flatten(items, trail) { for (const item of items) { const chain = [...trail, item.title]; if (item.href) leaves.push({ path: item.href, title: item.title, trail: chain.join(" → ") }); if (item.children) flatten(item.children, chain); } }
for (const group of navigation) flatten(group.items, []);
const routeSource = await source("src/lib/route-permissions.ts");
const features = await source("src/lib/plan-features.ts");
const permissionSource = await fs.readFile(path.resolve(backend, "../../prisma/seeds/shared/permissions.seed.ts"), "utf8");
const permissionTree = ts.createSourceFile("permissions.ts", permissionSource, ts.ScriptTarget.Latest, true);
const needed = new Set(["RESOURCES", "CRUD_ACTIONS", "ACTIONS", "SURFACES"]);
const permissionCode = permissionTree.statements.filter(statement =>
  ts.isFunctionDeclaration(statement) && statement.name?.text === "generateAllPermissions" ||
  ts.isVariableStatement(statement) && statement.declarationList.declarations.some(declaration => needed.has(declaration.name.getText(permissionTree)))
).map(statement => statement.getText(permissionTree)).join("\n");
const permissionJs = ts.transpileModule(permissionCode, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { generateAllPermissions } = await import(`data:text/javascript;base64,${Buffer.from(permissionJs).toString("base64")}`);
const content = {
  reviewedAt: HELP_REVIEWED_AT,
  guides: helpArticles.map(article => ({ slug: article.slug, title: article.title, summary: article.summary, keywords: article.keywords, path: `/help/${article.slug}`, sections: helpContent[article.slug] })),
  navigation: leaves, policies: assistantPolicies, permissions: generateAllPermissions(),
};
const hash = createHash("sha256").update(JSON.stringify(content) + routeSource + features).digest("hex");
const files = {
  "knowledge.generated.ts": `/* eslint-disable prettier/prettier */\n// Generated by ChurchOS-Web/scripts/sync-assistant-knowledge.mjs. Do not edit.\nexport const KNOWLEDGE_VERSION = '${hash}';\nexport const KNOWLEDGE: { reviewedAt: string; guides: { slug: string; title: string; summary: string; path: string; keywords: string[]; sections: { id: string; title: string; paragraphs?: string[]; steps?: string[]; bullets?: string[]; note?: string }[] }[]; navigation: { path: string; title: string; trail: string }[]; policies: { id: string; title: string; text: string }[]; permissions: { name: string; resource: string; action: string }[] } = ${JSON.stringify(content, null, 2)};\n`,
  "routes.generated.ts": `/* eslint-disable prettier/prettier */\n// Generated from the web route and plan maps. Do not edit.\n${routeSource}\n${features}`,
};
for (const [name, text] of Object.entries(files)) {
  const filename = path.join(backend, name);
  if (process.argv.includes("--check")) {
    if (await fs.readFile(filename, "utf8") !== text) throw new Error(`${name} is stale. Run npm run assistant:sync.`);
  } else { await fs.mkdir(backend, { recursive: true }); await fs.writeFile(filename, text); }
}
console.log(`Assistant knowledge ${hash.slice(0, 12)}: ${content.guides.length} guides, ${leaves.length} navigation entries, ${assistantPolicies.length} policies.`);
